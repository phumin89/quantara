const objectSchema = (schema) =>
  schema.properties.assessment.anyOf.find((item) => item.type === 'object');
const bound = objectSchema(CodexOutputSchema.create('reviewer', true, context));
for (const field of ['accountKey', 'runId', 'policyHash', 'asOf']) {
  assert.deepEqual(
    bound.properties[field].const,
    context[field],
    `Pinned ${field} must not be regenerated by the model.`,
  );
}
for (const field of ['thesis', 'reason']) {
  assert(
    new RegExp(bound.properties.positions.items.properties[field].pattern).test(
      'Supported evidence',
    ),
  );
  assert(
    !new RegExp(
      bound.properties.positions.items.properties[field].pattern,
    ).test(' \t\n'),
  );
}
const missing = bound.properties.positions.items.properties.missingFields.items;
assert.equal(missing.minLength, 1);
assert(!new RegExp(missing.pattern).test(''));
assert(!new RegExp(missing.pattern).test(' \t\n'));
assert(new RegExp(missing.pattern).test('entryThesis'));
for (const field of ['reason', 'reconsiderWhen']) {
  assert(
    !new RegExp(
      bound.properties.opportunities.items.properties[field].pattern,
    ).test(' \t\n'),
  );
}
