const reviewerSchema = CodexOutputSchema.create('reviewer', true, context);
for (const field of ['lesson', 'evidence', 'nextTest']) {
  const fieldSchema = reviewerSchema.properties.lesson.properties[field];
  const accepts = (value) =>
    value.length >= fieldSchema.minLength &&
    value.length <= fieldSchema.maxLength &&
    new RegExp(fieldSchema.pattern).test(value);
  for (const value of ['x', 'หลักฐานที่ตรวจได้', 'First line\nSecond line']) {
    assert(accepts(value));
    const lesson = { lesson: 'Known', evidence: 'Known', nextTest: 'Known' };
    lesson[field] = value;
    assert(CodexTeamWorker.validLesson('reviewer', lesson));
  }
  for (const value of [
    '',
    ' \t\n',
    ' padded',
    'padded ',
    'x\n',
    'x'.repeat(501),
  ]) {
    assert(!accepts(value), `Schema must reject invalid ${field}.`);
    const lesson = { lesson: 'Known', evidence: 'Known', nextTest: 'Known' };
    lesson[field] = value;
    assert(!CodexTeamWorker.validLesson('reviewer', lesson));
  }
}
assert(!new RegExp(reviewerSchema.properties.output.pattern).test(' \t\n'));
assert(CodexTeamWorker.validLesson('analyst', null));
assert(!CodexTeamWorker.validLesson('reviewer', null));
assert(!CodexTeamWorker.validLesson('reviewer', {}));
assert(
  !CodexTeamWorker.validLesson('reviewer', {
    lesson: 'Known',
    evidence: 'Known',
    nextTest: 'Known',
    extra: 'Unexpected',
  }),
);
